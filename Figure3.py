#################################################################
## python code for generating figures related to Figure3.
## Description: downsampling-based pseudobulk differential
## expression (SPF vs GF) for myeloid subsets; the resulting DEG
## tables are visualized in Figure3.R
## DEG tables for Figs 3b-3g and Figs s3a-s3h
#################################################################

import numpy as np
import pandas as pd
import scanpy as sc
import decoupler as dc
import matplotlib.pyplot as plt
import rpy2.robjects as ro
from pydeseq2.dds import DeseqDataSet, DefaultInference
from pydeseq2.ds import DeseqStats

## load downsampled UMI matrix (300 UMIs per cell;
## generated by metacell::scm_downsamp in Figure3.R, section "Data preparation")
adata = sc.read_h5ad('mye/data/seurat/v9_mye_mc2seu_downsample_300umi.h5ad')

## export all detected genes as the background gene set for GO enrichment (Figure3.R)
pd.DataFrame(adata.var_names, columns=['Symbol']).to_csv('mye/data/Mouse_54542g.csv')

#################################################################
## helper functions
#################################################################
readRDS = ro.r['readRDS']

def read_cutoff_cells(rds_path, key='cutoff15'):
    ## read cell lists filtered by minimal cell number per sample (from Figure3.R)
    return list(readRDS(rds_path).rx2(key))

def pseudobulk_deg(adata_target, out_csv,
                   design='~Group+Tissue_mod_only',
                   sample_col='Group_Tissue_Mouse',
                   groups_col=['Group', 'Tissue_mod_only'],
                   min_cells=10, min_counts=1000,
                   min_count=5, min_total_count=10,
                   drop_samples=None, n_cpus=8):
    ## pseudobulk (sum of counts) per Group-Tissue-Mouse combination,
    ## followed by DESeq2 (SPF vs GF) with pydeseq2
    adata_target.obs[sample_col] = (adata_target.obs.Group.astype('str') + '_' +
                                    adata_target.obs.Tissue_mod_only.astype('str') + '_' +
                                    adata_target.obs.Mouse.astype('str'))
    ## get pseudo-bulk profile
    pdata = dc.get_pseudobulk(adata_target,
                              sample_col=sample_col,
                              groups_col=groups_col,
                              mode='sum',
                              min_cells=min_cells,
                              min_counts=min_counts)
    ## remove outlier pseudobulk samples if needed
    if drop_samples is not None:
        pdata = pdata[~pdata.obs[sample_col].isin(drop_samples)]
    ## store raw counts in layers
    pdata.layers['counts'] = pdata.X.copy()
    ## normalize, scale and compute PCA (QC only)
    sc.pp.normalize_total(pdata, target_sum=1e4)
    sc.pp.log1p(pdata)
    sc.pp.scale(pdata, max_value=10)
    sc.tl.pca(pdata)
    ## return raw counts to X
    dc.swap_layer(pdata, 'counts', X_layer_key=None, inplace=True)
    pdata.obs[sample_col] = pdata.obs[sample_col].astype('category')
    ## filter lowly expressed genes
    genes = dc.filter_by_expr(pdata, group=groups_col,
                              min_count=min_count, min_total_count=min_total_count)
    pdata = pdata[:, genes].copy()
    ## build DESeq2 object and compute LFCs
    inference = DefaultInference(n_cpus=n_cpus)
    dds = DeseqDataSet(adata=pdata, design=design, refit_cooks=True, inference=inference)
    dds.deseq2()
    ## Wald test: SPF vs GF
    stat_res = DeseqStats(dds, contrast=['Group', 'SPF', 'GF'], inference=inference)
    stat_res.summary()
    results_df = stat_res.results_df
    results_df.to_csv(out_csv)
    return results_df

Time_list = ['P16', 'W4', 'W9']

#################################################################
## Monocytes (Mon): split into non-bm tissues and bm
## Figs 3b-3d, s3b, s3c, s3d
#################################################################
Mon_cells = read_cutoff_cells('mye/output/seurat/Mon_subset_cutoff_cells.rds')

## non-bm tissues (bm and skin excluded)
adata_Mon_ex_bm = adata[(adata.obs_names.isin(Mon_cells)) &
                        (~adata.obs.Tissue_mod_only.isin(['bm', 'skin']))].copy()
for time in Time_list:
    adata_target = adata_Mon_ex_bm[adata_Mon_ex_bm.obs.Time == time].copy()
    pseudobulk_deg(adata_target,
                   f'mye/output/scanpy/decoupler/Mon_exclude_bm_{time}_pseudobulk_deg_downsample300_cutoff15.csv')

## bm only (single tissue: design without Tissue_mod_only)
adata_Mon_bm = adata[(adata.obs_names.isin(Mon_cells)) &
                     (adata.obs.Tissue_mod_only == 'bm')].copy()
for time in Time_list:
    adata_target = adata_Mon_bm[adata_Mon_bm.obs.Time == time].copy()
    pseudobulk_deg(adata_target,
                   f'mye/output/scanpy/decoupler/Mon_bm_{time}_pseudobulk_deg_downsample300_cutoff15.csv',
                   design='~Group')

#################################################################
## Neutrophils (Neu)
## Figs s3e, s3g, s3h
#################################################################
Neu_cells = read_cutoff_cells('mye/output/seurat/Neu_subset_cutoff_cells.rds')
adata_Neu = adata[adata.obs_names.isin(Neu_cells)].copy()

## outlier pseudobulk samples removed per time point (based on pseudobulk QC plots)
Neu_drop_samples = {'P16': ['GF_lung_12', 'GF_bm_11'],
                    'W4': ['GF_lung_12'],
                    'W9': ['GF_bm_13', 'GF_heart_11']}
for time in Time_list:
    adata_target = adata_Neu[adata_Neu.obs.Time == time].copy()
    pseudobulk_deg(adata_target,
                   f'mye/output/scanpy/decoupler/Neu_{time}_pseudobulk_deg_downsample300_cutoff15.csv',
                   drop_samples=Neu_drop_samples[time])

#################################################################
## Macrophages (Mac)
## Figs 3e, 3f, s3f
#################################################################
Mac_cells = read_cutoff_cells('mye/output/seurat/Mac_subset_cutoff_cells.rds')
adata_Mac = adata[adata.obs_names.isin(Mac_cells)].copy()

for time in Time_list:
    adata_target = adata_Mac[adata_Mac.obs.Time == time].copy()
    pseudobulk_deg(adata_target,
                   f'mye/output/scanpy/decoupler/Mac_{time}_pseudobulk_deg_downsample300_cutoff15.csv')

#################################################################
## other 8 myeloid subsets: pseudobulk DEG per subset per time point
## data for Fig. s3a
#################################################################
CellType_list = ['Basophil', 'cDC1', 'cDC2_Ms4a4c', 'Mac_Il1b',
                 'Mon', 'Mon_bm', 'Neu_bm_Ccl6(Neg)', 'pDC']
for celltype in CellType_list:
    adata_subset = adata[adata.obs.annots == celltype].copy()
    for time in Time_list:
        adata_target = adata_subset[adata_subset.obs.Time == time].copy()
        pseudobulk_deg(adata_target,
                       f'mye/output/scanpy/decoupler/{celltype}_{time}_pseudobulk_deg_downsample300.csv')

#################################################################
## all 23 myeloid subsets: pseudobulk DEG per subset across all time points
## data for Fig. s3a (all-subset version)
#################################################################
CellType_list = ['Basophil', 'Eosinophil', 'KupfferCell', 'Langerhans', 'Mac_Il1b',
                 'Mac_Kidney', 'Mac_gut_Mmp9', 'Mac_skin', 'Mac_skin_Retnla', 'MastCell',
                 'Mon', 'Mon_bm', 'Neu_Il1b_Cxcl2', 'Neu_bm', 'Neu_bm_Ccl6(Neg)',
                 'Neu_bm_Stfa2', 'cDC1', 'cDC2_Mdh2', 'cDC2_Ms4a4c',
                 'cDC2_skin_Retnla(high)', 'cDC2_skin_Retnla(low)', 'mDC', 'pDC']
for celltype in CellType_list:
    adata_subset = adata[adata.obs.annots == celltype].copy()
    ## keep Group-Time-Mouse combinations with >= 10 cells
    g = adata_subset.obs.groupby(['Group', 'Time', 'Mouse']).size()
    keep_combo = g[g >= 10].index
    mask = adata_subset.obs.set_index(['Group', 'Time', 'Mouse']).index.isin(keep_combo)
    adata_subset = adata_subset[mask, :].copy()
    adata_subset.obs['Group_Time_Mouse'] = (adata_subset.obs.Group.astype('str') + '_' +
                                            adata_subset.obs.Time.astype('str') + '_' +
                                            adata_subset.obs.Mouse.astype('str'))
    pseudobulk_deg(adata_subset,
                   f'mye/output/scanpy/decoupler/{celltype}_pseudobulk_deg_downsample300.csv',
                   design='~Group+Time',
                   sample_col='Group_Time_Mouse',
                   groups_col=['Group', 'Time'],
                   min_count=10, min_total_count=15)
