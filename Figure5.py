def read_cutoff_cells(rds_path, key='cutoff15'):
    """Read the R list of per-cutoff cell barcodes (generated in Figure5.R)
    and return the cell IDs of the requested cutoff."""
    r_list = ro.r['readRDS'](rds_path)
    return list(r_list.rx2(key))


def pseudobulk_deg(adata_target, sample_col, groups_col, design,
                   out_csv, remove_samples=None,
                   min_cells=10, min_counts=1000,
                   min_count=5, min_total_count=10):
    """decoupler pseudobulk (sum of downsampled UMIs) + pydeseq2, SPF vs GF."""
    pdata = dc.get_pseudobulk(
        adata_target,
        sample_col=sample_col,
        groups_col=groups_col,
        mode='sum',
        min_cells=min_cells,
        min_counts=min_counts,
    )
    # exclude outlier pseudobulk samples (see per-subset notes below)
    if remove_samples:
        pdata = pdata[~pdata.obs[sample_col].isin(remove_samples)].copy()
    pdata.obs[sample_col] = pdata.obs[sample_col].astype('category')

    # store raw counts, normalize for PCA QC, then swap raw counts back to X
    pdata.layers['counts'] = pdata.X.copy()
    sc.pp.normalize_total(pdata, target_sum=1e4)
    sc.pp.log1p(pdata)
    sc.pp.scale(pdata, max_value=10)
    sc.tl.pca(pdata)
    dc.swap_layer(pdata, 'counts', X_layer_key=None, inplace=True)

    # gene filtering
    genes = dc.filter_by_expr(pdata, group=groups_col,
                              min_count=min_count, min_total_count=min_total_count)
    pdata = pdata[:, genes].copy()

    # DESeq2
    inference = DefaultInference(n_cpus=8)
    dds = DeseqDataSet(adata=pdata, design=design, refit_cooks=True, inference=inference)
    dds.deseq2()
    stat_res = DeseqStats(dds, contrast=['Group', 'SPF', 'GF'], inference=inference)
    stat_res.summary()
    results_df = stat_res.results_df
    results_df.to_csv(out_csv)
    print(out_csv)
    return results_df


