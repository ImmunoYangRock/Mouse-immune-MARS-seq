## Fig. S5f — Glycolysis / Oxidative phosphorylation / TCA cycle scores
#  projected on the metacell 2D map (SPF vs GF)
# =============================================================================
adata_mc = sc.read_h5ad('data/lym_umap_mc1.h5ad')

# GO term gene lists (MGI gene symbols in the first column)
oxy_go = pd.read_csv('ref/go_term/GO_term_0006119_oxidative_phosphorylation.txt', delimiter='\t').iloc[:, 0].values
tca_go = pd.read_csv('ref/go_term/GO_term_0006099_tricarboxylic_acid_cycle.txt', delimiter='\t').iloc[:, 0].values
