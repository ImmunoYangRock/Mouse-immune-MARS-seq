score_list = [gly_go, oxy_go, tca_go]
pool = ['Glycolysis Score', 'Oxidative Phosphorylation score', 'TCA Cycle Score']
for i, j in enumerate(pool):
    sc.tl.score_genes(adata_mc, gene_list=score_list[i], score_name=j)

# save per-cell scores
df = adata_mc.obs[pool + ['Group', 'Time', 'Tissue', 'annots']].copy()
df.to_csv('./lym/output/scanpy/v9_lym_Gly_Oxi_TCA_score.csv')

# projection: SPF (top) / GF (bottom) per score
fig, axes = plt.subplots(2, 3, figsize=(10, 6))
axes = axes.flatten()
for i, group in enumerate(pool):
    if group == 'Oxidative Phosphorylation score':
        vmax = 1.0
    elif group == 'Glycolysis Score':
        vmax = 0.30
    else:
        vmax = 0.8
    sc.pl.embedding(adata_mc[adata_mc.obs.Group.isin(['SPF'])], basis='X_metacell',
                    color=group, ax=axes[i], show=False, cmap='RdBu_r', vmax=vmax)
    axes[i].set_title(group + '_SPF')
    sc.pl.embedding(adata_mc[adata_mc.obs.Group.isin(['GF'])], basis='X_metacell',
                    color=group, ax=axes[i + 3], show=False, cmap='RdBu_r', vmax=vmax)
    axes[i + 3].set_title(group + '_GF')
plt.tight_layout()
plt.savefig('./lym/output/scanpy/v9_lym_Gly_Oxi_TCA_score.png')
